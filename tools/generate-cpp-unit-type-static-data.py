#!/usr/bin/env python3
"""Generate the C++ UnitType helper table from its tracked JSON authority."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "python" / "bwrapi" / "bwapi" / "unit_type_helpers.json"
OUTPUT = REPO_ROOT / "host" / "compatibility" / "src" / "UnitTypeStaticData.inc"
FIELDS = (
    "tileWidth",
    "tileHeight",
    "dimensionLeft",
    "dimensionUp",
    "dimensionRight",
    "dimensionDown",
    "whatBuildsUnitTypeId",
    "whatBuildsAmount",
    "requiresCreep",
    "isWorker",
    "isResourceDepot",
    "isResourceContainer",
)


def render() -> str:
    source_bytes = SOURCE.read_bytes()
    payload = json.loads(source_bytes)
    records = sorted(payload["records"], key=lambda record: int(record["id"]))
    expected_ids = list(range(len(records)))
    actual_ids = [int(record["id"]) for record in records]
    if actual_ids != expected_ids:
        raise ValueError("unit type helper ids must be contiguous and zero-based")

    lines = [
        "// Generated by tools/generate-cpp-unit-type-static-data.py.",
        "// Input: python/bwrapi/bwapi/unit_type_helpers.json",
        f"// Input SHA-256: {hashlib.sha256(source_bytes).hexdigest()}",
        "",
        "namespace {",
        "",
        "struct UnitTypeStaticData {",
        "    int id;",
        "    int tileWidth;",
        "    int tileHeight;",
        "    int dimensionLeft;",
        "    int dimensionUp;",
        "    int dimensionRight;",
        "    int dimensionDown;",
        "    int whatBuildsUnitTypeId;",
        "    int whatBuildsAmount;",
        "    bool requiresCreep;",
        "    bool isWorker;",
        "    bool isResourceDepot;",
        "    bool isResourceContainer;",
        "};",
        "",
        "constexpr UnitTypeStaticData kUnitTypeStaticData[] = {",
    ]
    for record in records:
        fields = record["fields"]
        values = [int(record["id"])]
        values.extend(fields[field] for field in FIELDS)
        rendered = ", ".join(_cpp_value(value) for value in values)
        lines.append(f"    {{{rendered}}},")
    lines.extend(
        (
            "};",
            "",
            "const UnitTypeStaticData* findUnitTypeStaticData(int id) {",
            "    if (id < 0) {",
            "        return nullptr;",
            "    }",
            "    const auto index = static_cast<unsigned int>(id);",
            (
                "    if (index >= (sizeof(kUnitTypeStaticData) / "
                "sizeof(kUnitTypeStaticData[0]))) {"
            ),
            "        return nullptr;",
            "    }",
            "    const auto& data = kUnitTypeStaticData[index];",
            "    return data.id == id ? &data : nullptr;",
            "}",
            "",
            "} // namespace",
            "",
        )
    )
    return "\n".join(lines)


def _cpp_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if type(value) is int:
        return str(value)
    raise TypeError(f"unsupported UnitType helper value: {value!r}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--check",
        action="store_true",
        help="fail when the tracked output differs",
    )
    mode.add_argument(
        "--write",
        action="store_true",
        help="replace the tracked output",
    )
    args = parser.parse_args()

    expected = render()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(
                "UnitTypeStaticData.inc is stale; rerun with --write"
            )
        return 0

    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
