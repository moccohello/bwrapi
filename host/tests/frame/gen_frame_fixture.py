"""Generates legacy44_frame_fixture.h from the bwrapi.h column lists.

    python gen_frame_fixture.py <path to bwrapi.h> <output header>

The fixture builds a BwrFrame out of row structs, so host tests can describe a
frame without writing one vector per column. CMake runs it at build time.
"""
import re
import sys

header = open(sys.argv[1], encoding="utf-8").read()
tables = re.findall(r"typedef struct (Bwr\w+) \{\s*size_t rows;(.*?)\} \1;", header, re.S)
frame = re.search(r"typedef struct BwrFrame \{(.*?)\} BwrFrame;", header, re.S).group(1)
members = re.findall(r"const (Bwr\w+)\* (\w+);", frame)
unknown = {
    "uint8_t": "UINT8_MAX", "uint16_t": "UINT16_MAX", "uint32_t": "UINT32_MAX",
    "uint64_t": "UINT64_MAX", "int16_t": "INT16_MIN", "int32_t": "INT32_MIN",
}

out = []
out.append("// Generated by gen_frame_fixture.py from bwrapi.h. Do not edit.")
out.append("#pragma once")
out.append("")
out.append('#include <bwrapi.h>')
out.append("")
out.append("#include <cstdint>")
out.append("#include <vector>")
out.append("")
out.append("namespace BWRAPI::Legacy44::Fixture {")
out.append("")
for name, body in tables:
    columns = re.findall(r"const (\w+)\* (\w+);", body)
    short = name[3:]
    out.append(f"// Rows of {name}; every column starts unknown.")
    out.append(f"struct {short}Rows {{")
    out.append("  struct Row {")
    for ctype, column in columns:
        if ctype in unknown:
            out.append(f"    {ctype} {column} = {unknown[ctype]};")
        else:
            out.append(f"    {ctype} {column}{{}};")
    out.append("  };")
    out.append("  std::vector<Row> rows;")
    for ctype, column in columns:
        out.append(f"  std::vector<{ctype}> c_{column};")
    out.append(f"  {name} view{{}};")
    out.append(f"  const {name}* build() {{")
    out.append("    view.rows = rows.size();")
    for _, column in columns:
        out.append(f"    c_{column}.clear();")
        out.append(f"    for (const auto& row : rows) c_{column}.push_back(row.{column});")
        out.append(f"    view.{column} = c_{column}.data();")
    out.append("    return &view;")
    out.append("  }")
    out.append("};")
    out.append("")
out.append("// All tables of a frame. A table is carried when it has rows or its source")
out.append("// bit is set in `carry`.")
out.append("struct FrameData {")
out.append("  std::uint32_t flags = 0;")
out.append("  std::uint64_t sequence = 1;")
out.append("  std::uint32_t match_id = 1;")
out.append("  std::uint32_t game_frame = 100;")
out.append("  std::uint16_t map_width = 0;")
out.append("  std::uint16_t map_height = 0;")
out.append("  std::uint8_t local_player = 255;")
out.append("  std::uint64_t carry = 0;")
for name, field in members:
    out.append(f"  {name[3:]}Rows {field};")
out.append("  BwrFrame frame{};")
out.append("  // Builds the C frame; the fixture must outlive it and stay unchanged.")
out.append("  const BwrFrame& build() {")
out.append("    frame = BwrFrame{};")
out.append("    frame.size = sizeof(BwrFrame);")
out.append("    frame.flags = flags;")
out.append("    frame.sequence = sequence;")
out.append("    frame.match_id = match_id;")
out.append("    frame.game_frame = game_frame;")
out.append("    frame.map_width = map_width;")
out.append("    frame.map_height = map_height;")
out.append("    frame.local_player = local_player;")
for _, field in members:
    out.append(f"    if (!{field}.rows.empty() || (carry & BWR_SOURCE_{field.upper()}) != 0) {{")
    out.append(f"      frame.{field} = {field}.build();")
    out.append(f"      frame.sources |= BWR_SOURCE_{field.upper()};")
    out.append("    }")
out.append("    return frame;")
out.append("  }")
out.append("};")
out.append("")
out.append("}  // namespace BWRAPI::Legacy44::Fixture")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
