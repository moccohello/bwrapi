"""Writes `bwapi/types.pyi`, `filters.pyi` and `input_text.pyi` from the real modules.

    python tests/generate_stubs.py          (from `python/`; rewrites the stubs)
    python tests/generate_stubs.py --check  (exit 1 when a stub differs)

Classes and signatures are copied from the module sources. The constants of the
`UnitTypes`-style namespaces, `Filter`, `Key`, `MouseButton` and `Text` are built
at import time, so they come from the live objects. Importing touches no game.
"""

from __future__ import annotations

import ast
import copy
import keyword
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1] / "bwrapi" / "bwapi"
sys.path.insert(0, str(PACKAGE.parents[1]))

from bwrapi.bwapi import filters, input_text, types  # noqa: E402

HEADER = "# Generated by tests/generate_stubs.py. Do not edit.\n"
# Comparison operators return filters, which the object signatures do not allow.
_OVERRIDES = {"__eq__", "__ne__"}


def _public(name: str) -> bool:
    return not name.startswith("_") or (name.startswith("__") and name.endswith("__"))


def _function(node: ast.FunctionDef, indent: str) -> list[str]:
    stub = copy.copy(node)
    stub.body = [ast.Expr(ast.Constant(...))]
    text = ast.unparse(stub).strip().replace(":\n    ...", ": ...")
    if node.name in _OVERRIDES:
        text += "  # type: ignore[override]"
    return [indent + line for line in text.split("\n")]


def _class(node: ast.ClassDef, indent: str = "") -> list[str]:
    body: list[str] = []
    for item in node.body:
        if isinstance(item, ast.FunctionDef) and _public(item.name):
            body += _function(item, indent + "    ")
        elif isinstance(item, ast.Assign) and _public(ast.unparse(item.targets[0])) and isinstance(item.value, ast.Name):
            body.append(indent + "    " + ast.unparse(item))
    bases = ", ".join(ast.unparse(base) for base in node.bases)
    head = f"{indent}class {node.name}({bases}):" if bases else f"{indent}class {node.name}:"
    return [head + " ..."] if not body else [head, *body]


def _source(path: Path) -> list[str]:
    """The public classes, functions and aliases of a module source."""
    lines: list[str] = []
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.ClassDef) and _public(node.name):
            lines += ["", *_class(node)]
        elif isinstance(node, ast.FunctionDef) and _public(node.name):
            lines += ["", *_function(node, "")]
        elif (isinstance(node, ast.Assign) and isinstance(node.value, ast.Name)
              and isinstance(node.targets[0], ast.Name) and _public(node.targets[0].id)):
            lines += ["", ast.unparse(node)]
    return lines


def _namespace(name: str, namespace: object, constant_types: tuple[type, ...], returns) -> list[str]:
    """A private class with one annotation per constant and the variable of that class."""
    lines = ["", f"class _{name}:"]
    for attribute, value in vars(namespace).items():
        if keyword.iskeyword(attribute):
            continue  # `None`, reachable through getattr; `None_` is its Python name.
        if isinstance(value, constant_types):
            lines.append(f"    {attribute}: {type(value).__name__}")
        elif callable(value):
            lines.append(f"    def {attribute}(self) -> {returns(attribute)}: ...")
        else:
            raise TypeError(f"{name}.{attribute}: unexpected {type(value).__name__}")
    return [*lines, "", f"{name}: _{name}"]


def _all(names: list[str]) -> list[str]:
    return ["", "__all__ = [", *[f'    "{name}",' for name in names], "]"]


def types_stub() -> str:
    lines = [HEADER.rstrip(), "from collections import deque", "from typing import Self", "",
             "from .containers import SetContainer", "from .position import TilePosition"]
    lines += _source(PACKAGE / "types.py")
    for name in types.__all__:
        namespace = getattr(types, name)
        if isinstance(namespace, type):
            continue
        item = name[:-1]  # UnitTypes holds UnitType values, Colors holds Color values, ...
        lines += _namespace(name, namespace, (types.Type,),
                            lambda method, item=item: "int" if method.startswith("max") else f"SetContainer[{item}]")
    return "\n".join([*lines, *_all(types.__all__)]) + "\n"


def filters_stub() -> str:
    lines = [HEADER.rstrip(), "from typing import Callable", "", "from .unit import Unit"]
    lines += _source(PACKAGE / "filters.py")
    lines += _namespace("Filter", filters.Filter, (filters.UnaryFilter, filters.CompareFilter), None)
    return "\n".join(lines) + "\n"


def _enum(name: str, members, indent: str = "") -> list[str]:
    return [f"{indent}class {name}(IntEnum):",
            *[f"{indent}    {key} = {int(value)}" for key, value in members.items() if not key.startswith("_")]]


def input_text_stub() -> str:
    text = input_text.Text
    size = text.Size
    lines = [HEADER.rstrip(), "from enum import IntEnum", "from typing import SupportsIndex", ""]
    lines += _enum("Key", input_text.Key.__members__) + [""]
    lines += _enum("MouseButton", input_text.MouseButton.__members__) + ["", "class Text:"]
    lines += _enum("Enum", text.Enum.__members__, "    ")
    lines += [f"    {key}: Enum" for key in text.Enum.__members__]
    lines += ["", "    class Size:", *_enum("Enum", size.Enum.__members__, "        ")]
    lines += [f"        {key}: Enum" for key in size.Enum.__members__]
    lines += ["", "    @staticmethod", "    def isColor(value: SupportsIndex) -> bool: ...", ""]
    lines += [f"{key}: Key" for key in input_text.Key.__members__ if key.startswith("K_")]
    lines += [f"{key}: MouseButton" for key in input_text.MouseButton.__members__ if key.startswith("M_")]
    return "\n".join([*lines, *_all(input_text.__all__)]) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    failed = False
    for name, text in (("types", types_stub()), ("filters", filters_stub()), ("input_text", input_text_stub())):
        path = PACKAGE / f"{name}.pyi"
        if not check:
            path.write_text(text, encoding="utf-8", newline="\n")
        elif not path.is_file() or path.read_text(encoding="utf-8") != text:
            print(f"out of date: {path}")
            failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
